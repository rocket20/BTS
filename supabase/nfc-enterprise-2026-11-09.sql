create schema if not exists bts_private;
revoke all on schema bts_private from public, anon, authenticated;

create table if not exists public.bts_nfc_executives (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.bts_nfc_cards(id) on delete cascade,
 card_code text not null unique default substring(replace(gen_random_uuid()::text,'-','') from 1 for 20)
   check (card_code ~ '^[a-f0-9]{20}$'),
 card_label text not null default 'Tarjeta NFC' check(char_length(card_label) between 1 and 70),
 full_name text not null check(char_length(full_name) between 2 and 100),
 job_title text not null default '' check(char_length(job_title) <= 90),
 whatsapp_number text not null check(whatsapp_number ~ '^\+?[0-9]{7,15}$'),
 phone_number text not null default '' check(phone_number = '' or phone_number ~ '^\+?[0-9]{7,15}$'),
 email text not null default '' check(char_length(email) <= 150),
 avatar_url text not null default '' check(char_length(avatar_url) <= 1000),
 extra_links jsonb not null default '[]'::jsonb
   check (jsonb_typeof(extra_links)='array' and jsonb_array_length(extra_links)<=6),
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists bts_nfc_executives_company_idx on public.bts_nfc_executives(company_id,created_at desc);
create index if not exists bts_nfc_executives_active_company_idx on public.bts_nfc_executives(company_id,card_code) where is_active;
alter table public.bts_nfc_executives enable row level security;
drop policy if exists bts_nfc_executives_public on public.bts_nfc_executives;
create policy bts_nfc_executives_public on public.bts_nfc_executives for select to anon,authenticated
 using (is_active and exists(select 1 from public.bts_nfc_cards c where c.id=company_id and c.is_active));
drop policy if exists bts_nfc_executives_admin on public.bts_nfc_executives;
create policy bts_nfc_executives_admin on public.bts_nfc_executives for all to authenticated
 using (exists (select 1 from public.bts_admins a where a.user_id=(select auth.uid())))
 with check (exists (select 1 from public.bts_admins a where a.user_id=(select auth.uid())));
revoke all on public.bts_nfc_executives from anon,authenticated;
grant select on public.bts_nfc_executives to anon;
grant select,insert,update,delete on public.bts_nfc_executives to authenticated;

create table if not exists public.bts_nfc_pricing (
