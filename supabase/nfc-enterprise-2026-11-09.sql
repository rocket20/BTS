create table if not exists public.bts_nfc_events (
 id bigint generated by default as identity primary key,
 executive_id uuid not null references public.bts_nfc_executives(id) on delete cascade,
 event_type text not null check(event_type in ('visit','whatsapp_click','link_click','contact_download')),
 link_type text not null default '' check(char_length(link_type)<=35),
 created_at timestamptz not null default now()
);
create index if not exists bts_nfc_events_exec_date_idx on public.bts_nfc_events(executive_id,created_at desc);
alter table public.bts_nfc_events enable row level security;
drop policy if exists bts_nfc_events_public_insert on public.bts_nfc_events;
create policy bts_nfc_events_public_insert on public.bts_nfc_events for insert to anon,authenticated
 with check (exists(select 1 from public.bts_nfc_executives e
   join public.bts_nfc_cards c on c.id=e.company_id
   where e.id=executive_id and e.is_active and c.is_active));
drop policy if exists bts_nfc_events_admin_read on public.bts_nfc_events;
create policy bts_nfc_events_admin_read on public.bts_nfc_events for select to authenticated
 using (exists(select 1 from public.bts_admins a where a.user_id=(select auth.uid())));
revoke all on public.bts_nfc_events from anon,authenticated;
grant insert on public.bts_nfc_events to anon,authenticated;
grant select on public.bts_nfc_events to authenticated;
grant usage on sequence public.bts_nfc_events_id_seq to anon,authenticated;

create table if not exists public.bts_nfc_executive_audit (
 id bigint generated by default as identity primary key,
