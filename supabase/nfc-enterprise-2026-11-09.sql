create or replace function bts_private.nfc_executive_before_update()
returns trigger language plpgsql set search_path = '' as $$
begin
 if new.card_code is distinct from old.card_code then
   raise exception 'La URL física de una tarjeta NFC no se puede cambiar';
 end if;
 new.updated_at=now();
 return new;
end;
$$;
revoke all on function bts_private.nfc_executive_before_update() from public,anon,authenticated;
drop trigger if exists bts_nfc_executive_before_update on public.bts_nfc_executives;
create trigger bts_nfc_executive_before_update before update on public.bts_nfc_executives
 for each row execute function bts_private.nfc_executive_before_update();

create or replace function bts_private.nfc_executive_audit_event()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 if tg_op='DELETE' then
   insert into public.bts_nfc_executive_audit(company_id,executive_id,operation,before_data,actor_id)
   values(old.company_id,old.id,tg_op,to_jsonb(old),auth.uid());
   return old;
 else
   insert into public.bts_nfc_executive_audit(company_id,executive_id,operation,before_data,after_data,actor_id)
   values(new.company_id,new.id,tg_op,
      case when tg_op='UPDATE' then to_jsonb(old) else null end,to_jsonb(new),auth.uid());
   return new;
 end if;
end;
$$;
revoke all on function bts_private.nfc_executive_audit_event() from public,anon,authenticated;
drop trigger if exists bts_nfc_executives_audit on public.bts_nfc_executives;
create trigger bts_nfc_executives_audit after insert or update or delete on public.bts_nfc_executives
 for each row execute function bts_private.nfc_executive_audit_event();
